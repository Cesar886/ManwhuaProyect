export function getAllPosts() {
  return [...POSTS].sort((a, b) => new Date(b.publishedAt) - new Date(a.publishedAt))
}

export function getPostBySlug(slug) {
  return POSTS.find((p) => p.slug === slug) || null
}

export function getPostsByCategory(category) {
  return POSTS.filter((p) => p.category === category).sort(
    (a, b) => new Date(b.publishedAt) - new Date(a.publishedAt)
  )
}

export function getRecentPosts(count = 3) {
  return getAllPosts().slice(0, count)
}

export function getAllSlugs() {
  return POSTS.map((p) => p.slug)
}

/** Añade un post al array en runtime (no persiste; usar solo en dev/scripts) */
export function addPost(post) {
  if (!post.slug || POSTS.find((p) => p.slug === post.slug)) return false
  POSTS.push(post)
  return true
}
